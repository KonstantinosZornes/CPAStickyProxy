const dictionaries: Record<Language, Dictionary> = { zh, en };

export function t(
  key: string,
  language: Language,
  values: Record<string, string | number> = {},
): string {
  return (dictionaries[language][key] ?? dictionaries.en[key] ?? key).replace(
    /\{(\w+)\}/g,
    (_, name: string) => String(values[name] ?? ""),
  );
}

export function errorMessage(
  code: string | undefined,
  language: Language,
): string {
  return t(code || "request_failed", language);
}
